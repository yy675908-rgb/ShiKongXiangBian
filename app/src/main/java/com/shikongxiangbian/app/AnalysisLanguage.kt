    fun text(raw: String): String {
        val direct = raw.replace(Regex("约束经([木火土金水])转接的承载尚待检，不能直接按生扶论")) {
            "约束能否经${it.groupValues[1]}转为生扶，仍待判断"
        }
        return wording.fold(direct) { value, (from, to) -> value.replace(from, to) }
    }

    /** Combine identical qualifications, without removing any direction or condition. */
    fun changes(raw: List<String>): List<String> {
        val groups = linkedMapOf<String, MutableList<String>>()
        raw.distinct().forEach { line ->
            val suffix = listOf("新增可用承接候选", "承接转为待检", "显性节点补齐，承载待检").firstOrNull { line.endsWith(it) }
            if (suffix == null) groups.getOrPut("\u0000$line") { mutableListOf() }
            else groups.getOrPut(suffix) { mutableListOf() }.add(line.removeSuffix(suffix))
        }
        return groups.map { (suffix, routes) ->
            text(if (suffix.startsWith("\u0000")) suffix.drop(1) else routes.joinToString("；") + "：" + suffix)
        }
    }
